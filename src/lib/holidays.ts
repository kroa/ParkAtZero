let holidaySet = new Set<string>([...HOLIDAYS_2025, ...HOLIDAYS_2026, ...HOLIDAYS_2027])

/** 외부(공공데이터포털 특일정보 API 등)에서 받아온 공휴일 목록으로 교체 */
export function setHolidaySource(dates: string[]): void {
  holidaySet = new Set(dates)
}

/** 로컬 타임존 기준 YYYY-MM-DD */
export function toDateKey(d: Date): string {
  const y = d.getFullYear()
  const m = String(d.getMonth() + 1).padStart(2, '0')
  const day = String(d.getDate()).padStart(2, '0')
  return `${y}-${m}-${day}`
}

export function isPublicHoliday(d: Date): boolean {
  return holidaySet.has(toDateKey(d))
}

/** 공휴일 이름을 알 필요는 없고, '공휴일이냐'만 판정하면 되는 앱이라 boolean 만 노출한다. */
export function isSunday(d: Date): boolean {
  return d.getDay() === 0
}

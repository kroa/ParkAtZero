/*
 * '전남광주통합특별시' 는 전남과 광주를 아우르는 이름으로 데이터에 섞여 들어온다
 * (자치법규 검색에도 같은 이름이 나온다). 같은 지역이 '전라남도'·'광주광역시' 로도
 * 들어와 있어 그대로 두면 여수시 페이지가 둘로 갈린다.
 * 시군구 이름으로 갈라 기존 지역에 합친다 — 광주 자치구 다섯은 광주광역시로, 나머지는 전라남도로.
 */
const GWANGJU_GU = new Set(['동구', '서구', '남구', '북구', '광산구'])
const MERGED_SIDO = '전남광주통합특별시'

/** 시도 이름이 시군구까지 붙어 있을 때 떼어내기 위한 접두사 목록(긴 것부터) */
const SIDO_PREFIXES = [...new Set(Object.keys(SIDO_ALIAS))].sort((a, b) => b.length - a.length)

/** 시군구로 인정할 꼬리. 이게 없으면 동·리 이름이 잘못 올라온 것이다. */
const SGG_TAIL = /(시|군|구)$/

const squash = (s) => String(s ?? '').replace(/\s+/g, ' ').trim()

/**
 * 주소 → { sido, sgg } 또는 null.
 * 세종특별자치시처럼 시군구가 없는 곳은 sgg 가 빈 문자열이다.
 */
export function parseRegion(address) {
  let a = squash(address)
  if (!a || a === '데이터값없음') return null

  // '경기도동두천시평화로 2687' 처럼 붙여 쓴 것을 떼어 준다.
  if (!a.includes(' ')) {
    for (const p of SIDO_PREFIXES) {
      if (a.startsWith(p) && a.length > p.length) {
        a = p + ' ' + a.slice(p.length)
        break
      }
    }
  }

  const words = a.split(' ')

  if (words[0] === MERGED_SIDO) {
    const sgg = words[1] ?? ''
    if (!SGG_TAIL.test(sgg)) return null
    return { sido: GWANGJU_GU.has(sgg) ? '광주광역시' : '전라남도', sgg }
  }

  const sido = SIDO_ALIAS[words[0]]
  if (!sido) return null

  if (sido === '세종특별자치시') return { sido, sgg: '' }

  let rest = words.slice(1).join(' ')
  // 시도명이 시군구에 다시 붙어 있는 경우('강원특별자치도강릉시 교동' → 이미 위에서 분리됨)
  let sgg = rest.split(' ')[0] ?? ''

  /*
   * '수원시 팔달구' 처럼 시 아래 구가 있는 곳은 시까지만 쓴다.
   * 구 단위로 쪼개면 페이지가 잘게 흩어져 각각 내용이 얇아진다.
   */
  if (!SGG_TAIL.test(sgg)) return null
  // '북구'·'산격동' 처럼 시도 없이 시군구만 온 잘못된 주소는 위에서 이미 걸린다.
  if (sgg.length < 2) return null

  return { sido, sgg }
}

/** 지역 페이지 경로. 한글 그대로 쓰되 URL 로 안전하게 인코딩한다. */
export function regionPath(sido, sgg) {
  return sgg ? `/지역/${sido}/${sgg}/` : `/지역/${sido}/`
}

export function encodePath(p) {
  return p
    .split('/')
    .map((seg) => (seg ? encodeURIComponent(seg) : seg))
    .join('/')
}
